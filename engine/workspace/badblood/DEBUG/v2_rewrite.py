def main() -> None:
    g = json.loads(DATA.read_text(encoding="utf-8"))
    idx = {c["id"]: c for c in g["cards"]}
    missed = []
    for cid, table in PATCHES.items():
        card = idx[cid]
        done = set()
        for seg in card["segments"]:
            if seg["text"] in table:
                seg["text"] = table[seg["text"]]
                done.add(seg["text"])
        for old, new in table.items():
            if new not in done and not any(s["text"] == new for s in card["segments"]):
                missed.append(f"{cid}: 未匹配到原文 → {old[:24]}…")
    DATA.write_text(json.dumps(g, ensure_ascii=False, indent=1), encoding="utf-8")
    print("人物塑造与去重改写完成：" + "、".join(PATCHES))
    for m in missed:
        print("WARN", m)


if __name__ == "__main__":
    main()
