def main() -> None:
    g = json.loads(DATA.read_text(encoding="utf-8"))

    cols = g["timelines"]["3"]["cols"]
    if "格伦兹" not in cols:
        cols.append("格伦兹")

    idx = {c["id"]: i for i, c in enumerate(g["cards"])}
    for card in (C3_25, C3_26, C3_27, C3_28):
        if card["id"] in idx:
            g["cards"][idx[card["id"]]] = card
        else:
            g["cards"].append(card)

    idx = {c["id"]: i for i, c in enumerate(g["cards"])}

    def patch(cid: str, table: dict) -> None:
        for seg in g["cards"][idx[cid]]["segments"]:
            if seg["text"] in table:
                seg["text"] = table[seg["text"]]

    patch("c3_01", C3_01_FIX)
    patch("c3_03", C3_03_FIX)
    patch("c3_09", C3_09_FIX)

    # c3_01 的加德纳、c3_03 的桑德内/格伦兹：配角文本名 → 词条气泡
    for seg in g["cards"][idx["c3_01"]]["segments"]:
        if seg.get("speaker") == "加德纳":
            del seg["speaker"]
            seg["speakerEntry"] = "e_gardner"
    for seg in g["cards"][idx["c3_03"]]["segments"]:
        sp = seg.get("speaker")
        if sp in C3_03_SPEAKER_FIX:
            del seg["speaker"]
            seg["speakerEntry"] = C3_03_SPEAKER_FIX[sp]
            if C3_03_SPEAKER_FIX[sp] == "e_glunz":
                seg["text"] = C3_03_GLUNZ_LINE

    g["cards"].sort(key=lambda c: c["id"])
    DATA.write_text(json.dumps(g, ensure_ascii=False, indent=1), encoding="utf-8")
    print("卷3 改造完成：+c3_25 +c3_26 +c3_27 +c3_28，配角升格，去重与富兹动机延续")


if __name__ == "__main__":
    main()
