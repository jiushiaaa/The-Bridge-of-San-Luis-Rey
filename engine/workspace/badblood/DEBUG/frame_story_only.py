# ---------------------------------------------------------------- c2_22 自白改写
C2_22_OLD = "全世界都在等我把它交出来——剩下的事只有一件：让机器赶上我说过的话。"
C2_22_NEW = "全世界都在等我把它交出来——我从不怀疑：话先立在那里，机器就一定会赶上来。"


def main() -> None:
    g = json.loads(DATA.read_text(encoding="utf-8"))

    g["meta"]["subtitle"] = "一个硅谷巨头的秘密与谎言"
    g["frame"]["levelIntro"]["1"] = LEVEL_INTRO_1
    g["frame"]["levelIntro"]["2"] = LEVEL_INTRO_2
    g["frame"]["levelIntro"]["3"] = LEVEL_INTRO_3
    g["frame"]["ending"]["title"] = "尾声 · 尘埃落定"
    g["frame"]["ending"]["segments"] = ENDING_SEGMENTS
    g["frame"]["ending"]["credit"] = "坏血 · 一个硅谷巨头的秘密与谎言 · 改编自约翰·卡雷鲁同名纪实作品 · 幻光文游"

    pages = g["entries"]["e_fuisz"]["archive"]
    for i, p in enumerate(pages):
        if p["level"] == 1:
            pages[i] = FUISZ_PAGE_1
            break
    else:
        raise SystemExit("e_fuisz 第 1 关档案页未找到")

    hit = 0
    for c in g["cards"]:
        if c["id"] != "c2_22":
            continue
        for s in c["segments"]:
            if C2_22_OLD in s["text"]:
                s["text"] = s["text"].replace(C2_22_OLD, C2_22_NEW)
                hit += 1
    if hit == 0 and C2_22_NEW not in json.dumps(g, ensure_ascii=False):
        raise SystemExit("c2_22 待改写句未找到")

    DATA.write_text(json.dumps(g, ensure_ascii=False, indent=1), encoding="utf-8")
    print("过场 %d/%d/%d 段，结局 %d 段；e_fuisz 第1关档案页 %d 字段 %d 留白；c2_22 改写 %d 处"
          % (len(LEVEL_INTRO_1), len(LEVEL_INTRO_2), len(LEVEL_INTRO_3), len(ENDING_SEGMENTS),
             len(FUISZ_PAGE_1["fields"]),
             sum(1 for f in FUISZ_PAGE_1["fields"] if "blank" in f), hit))


if __name__ == "__main__":
    main()
