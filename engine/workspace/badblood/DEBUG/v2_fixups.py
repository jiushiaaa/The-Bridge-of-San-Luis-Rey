# ---------------------------------------------------------- 字数档校准
LEN_PATCHES = {"c2_09": "M", "c2_23": "L"}

# ---------------------------------------------------------- 档案留白去重（换掉重复答案）
BLANK_SWAPS = {
    # 词条 id: (页标题, 旧 label, 新 label, 新答案, pool)
    "e_jay": ("铁杆鼓吹者", "他推动签约的公司总部", "和他一起闪电签约的财务掌门", "e_miquelon", "person"),
    "e_yamamoto": ("巡视员", "两次检查的工厂", "他第一次突检时被挡在门外的那栋楼", "e_facebook", "place"),
    "e_tkemp": ("发送结果的人", "演示发生地", "他守在加州那栋旧楼里发出了结果", "e_dongpaluo", "place"),
}


def main() -> None:
    g = json.loads(DATA.read_text(encoding="utf-8"))
    idx = {c["id"]: c for c in g["cards"]}

    for cid, table in TEXT_PATCHES.items():
        for seg in idx[cid]["segments"]:
            if seg["text"] in table:
                seg["text"] = table[seg["text"]]

    # c2_03 的杜普伊：配角文本名 → 词条气泡（她已升格为人物词条）
    for seg in idx["c2_03"]["segments"]:
        if seg.get("speaker") == "杜普伊":
            del seg["speaker"]
            seg["speakerEntry"] = "e_dupuy"

    for cid, lv in LEN_PATCHES.items():
        idx[cid]["len"] = lv

    for eid, (title, old_label, new_label, answer, pool) in BLANK_SWAPS.items():
        for page in g["entries"][eid]["archive"]:
            if page["title"] != title:
                continue
            for f in page["fields"]:
                if f.get("label") == old_label and "blank" in f:
                    f["label"] = new_label
                    f["blank"] = {"answer": answer, "pool": pool}

    DATA.write_text(json.dumps(g, ensure_ascii=False, indent=1), encoding="utf-8")
    print("收尾修补完成：speaker 升格、chip 补种、字数档校准、留白去重")


if __name__ == "__main__":
    main()
